export function normalizeLegacyMap(content: string): string {
  const version = content.match(/^- (?:合同版本|格式版本)[：:]\s*([123])\s*$/m)?.[1];
  if (!version || version === "3") return content;
  for (const [oldName, newName] of aliases) {
    const escaped = oldName.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    content = content.replace(new RegExp(`(^- |[｜|]\\s*)${escaped}([：:])`, "gm"), `$1${newName}$2`);
  }
  return content
    .replace(/(决定[：:]\s*)留在后台/g, "$1仅供备查")
    .replace(/(角色[：:]\s*)中心/g, "$1核心")
    .replace(/(角色[：:]\s*)必要/g, "$1补充")
    .replace(/(角色[：:]\s*)(?:后台|研究记录)/g, "$1备查");
}
